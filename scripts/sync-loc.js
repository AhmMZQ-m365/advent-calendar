/**
 * Localized strings: src/webparts/adventCalendar/loc/
 *  - fr-fr.js and en-us.js are both maintained by hand (en-us.js is also SPFx's fallback for any other language);
 *  - this script generates mystrings.d.ts (typing) from fr-fr.js;
 *  - fails if fr-fr.js and en-us.js do not have exactly the same keys;
 *  - fails if a `strings.X` used in the code is missing; reports unused keys.
 * Usage: npm run loc
 */
'use strict';

const fs = require('fs');
const path = require('path');

const locDir = path.join(__dirname, '..', 'src', 'webparts', 'adventCalendar', 'loc');
const srcDir = path.join(__dirname, '..', 'src');
const SOURCES = ['fr-fr.js', 'en-us.js'];

/** Evaluates an AMD loc module (`define([], function () { return {…}; })`) and returns its object. */
function loadStrings(fileName) {
  const source = fs.readFileSync(path.join(locDir, fileName), 'utf8');
  let strings;
  new Function('define', source)((_deps, factory) => {
    strings = factory();
  });
  if (!strings || typeof strings !== 'object') {
    throw new Error(`${fileName}: the module does not return a strings object.`);
  }
  return strings;
}

const [frStrings, enStrings] = SOURCES.map(loadStrings);
const frKeys = Object.keys(frStrings);
const enKeys = Object.keys(enStrings);

// 1. Strict key parity between the two languages.
const missingInEn = frKeys.filter((key) => !(key in enStrings));
const missingInFr = enKeys.filter((key) => !(key in frStrings));
if (missingInEn.length > 0 || missingInFr.length > 0) {
  console.error('Localization error: fr-fr.js and en-us.js must define exactly the same keys.');
  if (missingInEn.length > 0) {
    console.error(`  Missing in en-us.js (${missingInEn.length}): ${missingInEn.join(', ')}`);
  }
  if (missingInFr.length > 0) {
    console.error(`  Missing in fr-fr.js (${missingInFr.length}): ${missingInFr.join(', ')}`);
  }
  process.exit(1);
}

// 2. Same value type (string / string[]) on both sides.
const typeOf = (value) => (Array.isArray(value) ? 'string[]' : 'string');
const typeMismatches = frKeys.filter((key) => typeOf(frStrings[key]) !== typeOf(enStrings[key]));
if (typeMismatches.length > 0) {
  console.error(`Localization error: value type differs between fr-fr.js and en-us.js for: ${typeMismatches.join(', ')}`);
  process.exit(1);
}

// 3. Typing generated from fr-fr.js.
const declarations = frKeys.map((key) => `  ${key}: ${typeOf(frStrings[key])};`).join('\n');
fs.writeFileSync(
  path.join(locDir, 'mystrings.d.ts'),
  `// Generated by scripts/sync-loc.js from fr-fr.js: do not edit by hand.
declare interface IAdventCalendarWebPartStrings {
${declarations}
}

declare module 'AdventCalendarWebPartStrings' {
  const strings: IAdventCalendarWebPartStrings;
  export = strings;
}
`
);

// 4. Keys used in the code but not defined; keys defined but never used.
function walk(dir) {
  return fs.readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      return walk(full);
    }
    return /\.tsx?$/.test(entry.name) ? [full] : [];
  });
}

const used = new Set();
for (const file of walk(srcDir)) {
  for (const match of fs.readFileSync(file, 'utf8').matchAll(/\bstrings\.([A-Za-z0-9_]+)/g)) {
    used.add(match[1]);
  }
}
const missing = [...used].filter((key) => !(key in frStrings));
const unused = frKeys.filter((key) => !used.has(key));

if (unused.length > 0) {
  console.warn(`Unused localized strings: ${unused.join(', ')}`);
}
if (missing.length > 0) {
  console.error(`Localization error: strings used in the code but missing from fr-fr.js and en-us.js: ${missing.join(', ')}`);
  process.exit(1);
}
console.log(`${frKeys.length} localized strings checked (fr-fr.js = en-us.js), mystrings.d.ts generated.`);
